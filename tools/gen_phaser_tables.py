#!/usr/bin/env python3
"""Generate a logarithmic sweep of the first four-stage notch, at 32 kHz.

All frequency/trigonometric work is offline. The RSP still loads one 32-byte
book per stage. Keep coefficients strictly inside (-1, 1) for stable poles.
"""
import math
from pathlib import Path

REFERENCE_RATE = 32000
MIN_NOTCH_HZ = 50
MAX_NOTCH_HZ = 8000
POSITIONS = 127


def coefficient_for_index(index):
    frequency = MIN_NOTCH_HZ * (MAX_NOTCH_HZ / MIN_NOTCH_HZ) ** (index / (POSITIONS - 1))
    ratio = math.tan(math.pi * frequency / REFERENCE_RATE) / math.tan(math.pi / 8)
    coefficient = round(16384 * (1 - ratio) / (1 + ratio))
    return max(-16000, min(16000, coefficient))


def generate():
    lines = [
        "/* Generated by tools/gen_phaser_tables.py; Q14 powers for the stock POLEF command. */",
        f"static const s16 sPhaserBook[{POSITIONS}][16] __attribute__((aligned(16))) = {{",
    ]
    for index in range(POSITIONS):
        coefficient = coefficient_for_index(index)
        powers = [
            (coefficient**n + 16384**(n - 1) // 2) // 16384**(n - 1)
            for n in range(1, 9)
        ]
        lines.append("    { " + ", ".join(map(str, [0] * 8 + powers)) + " },")
    return "\n".join(lines + ["};", ""])


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "src/audio/phaser_tables.inc.c"
    destination.write_text(generate())
